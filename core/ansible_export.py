"""Ansible inventory export helpers."""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

from core.inventory import collect_inventory
from core.util import ensure_dir


def _sanitize_hostname(name: str) -> str:
    safe = "".join(c if c.isalnum() or c in "-_." else "-" for c in name.strip())
    return safe or "host"


def inventory_from_local(
    *,
    ansible_host: Optional[str] = None,
    ansible_user: Optional[str] = None,
    groups: Optional[List[str]] = None,
) -> Dict[str, Any]:
    """Build an Ansible-style inventory dict for the local host."""
    inv = collect_inventory()
    host = _sanitize_hostname(str(inv.get("hostname") or "localhost"))
    os_info = inv.get("os") or {}
    vars_ = {
        "ansible_connection": "local",
        "sai_os_id": os_info.get("id"),
        "sai_os_family": os_info.get("family"),
        "sai_os_version": os_info.get("version_id") or os_info.get("version"),
        "sai_pretty_name": os_info.get("pretty_name"),
        "sai_pkg_manager": os_info.get("pkg_manager"),
        "sai_firewall": os_info.get("firewall"),
        "sai_kernel": inv.get("kernel"),
        "sai_cpus": inv.get("cpus"),
        "sai_virtualization": inv.get("virtualization"),
        "sai_collected_at": inv.get("collected_at"),
    }
    if ansible_host:
        vars_["ansible_host"] = ansible_host
        vars_["ansible_connection"] = "ssh"
    if ansible_user:
        vars_["ansible_user"] = ansible_user

    group_map: Dict[str, Any] = {
        "all": {
            "hosts": {host: vars_},
            "children": {},
        }
    }
    for g in groups or []:
        gname = _sanitize_hostname(g).replace(".", "_")
        group_map["all"]["children"][gname] = {"hosts": {host: None}}
    # Convenience groups by OS family / id
    family = str(os_info.get("family") or "unknown")
    os_id = str(os_info.get("id") or "unknown")
    group_map["all"]["children"][f"sai_family_{family}"] = {"hosts": {host: None}}
    group_map["all"]["children"][f"sai_os_{os_id}"] = {"hosts": {host: None}}
    return group_map


def inventory_from_fleet_hosts(
    hosts: List[Dict[str, Any]],
    *,
    results: Optional[Dict[str, Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """
    Build Ansible inventory from fleet host definitions.
    Optional results: name -> {summary, ok, error} for grouping.
    """
    all_hosts: Dict[str, Any] = {}
    children: Dict[str, Any] = {
        "sai_ok": {"hosts": {}},
        "sai_issues": {"hosts": {}},
        "sai_unreachable": {"hosts": {}},
    }
    for h in hosts:
        name = _sanitize_hostname(str(h.get("name") or h.get("host") or "host"))
        host_vars = {
            "ansible_host": h.get("host") or h.get("ansible_host") or name,
            "ansible_user": h.get("user") or h.get("ansible_user") or "root",
            "ansible_port": int(h.get("port") or h.get("ansible_port") or 22),
        }
        if h.get("key"):
            host_vars["ansible_ssh_private_key_file"] = h["key"]
        for k, v in (h.get("vars") or {}).items():
            host_vars[k] = v
        all_hosts[name] = host_vars

        for g in h.get("groups") or []:
            gname = _sanitize_hostname(str(g)).replace(".", "_")
            children.setdefault(gname, {"hosts": {}})
            children[gname]["hosts"][name] = None

        if results and name in results:
            r = results[name]
            if r.get("error"):
                children["sai_unreachable"]["hosts"][name] = None
            else:
                summary = r.get("summary") or {}
                crit = int(summary.get("critical", 0)) + int(summary.get("high", 0))
                if crit > 0:
                    children["sai_issues"]["hosts"][name] = None
                    host_vars["sai_critical_or_high"] = crit
                else:
                    children["sai_ok"]["hosts"][name] = None
                host_vars["sai_finding_total"] = int(summary.get("total", 0))

    # Drop empty dynamic groups for cleaner inventory
    children = {k: v for k, v in children.items() if v.get("hosts")}
    return {"all": {"hosts": all_hosts, "children": children}}


def to_yaml(inventory: Dict[str, Any]) -> str:
    return yaml.safe_dump(inventory, default_flow_style=False, sort_keys=False)


def to_ini(inventory: Dict[str, Any]) -> str:
    """Render a simple INI inventory from our YAML-shaped dict."""
    lines: List[str] = [
        f"; Generated by Server AI Assistant at {datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}",
        "",
    ]
    all_block = inventory.get("all") or {}
    hosts = all_block.get("hosts") or {}
    lines.append("[all]")
    for name, vars_ in hosts.items():
        if not vars_:
            lines.append(name)
            continue
        parts = [name]
        for k, v in vars_.items():
            if v is None:
                continue
            parts.append(f"{k}={v}")
        lines.append(" ".join(parts))
    lines.append("")
    for gname, gdata in (all_block.get("children") or {}).items():
        lines.append(f"[{gname}]")
        for hname in (gdata.get("hosts") or {}):
            lines.append(hname)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_inventory(inventory: Dict[str, Any], path: Path, *, fmt: str = "yaml") -> Path:
    ensure_dir(path.parent)
    if fmt == "ini":
        path.write_text(to_ini(inventory), encoding="utf-8")
    else:
        path.write_text(to_yaml(inventory), encoding="utf-8")
    return path
